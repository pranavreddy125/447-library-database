-- Run before 02_operations.sql
BEGIN;
CREATE SCHEMA library;
REVOKE ALL ON SCHEMA library FROM PUBLIC;
ALTER DEFAULT PRIVILEGES IN SCHEMA library REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;

CREATE TABLE library.membership_type (
    membership_type_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (membership_type_id > 0),
    name VARCHAR(50) NOT NULL CHECK (name ~ '[^[:space:]]'),
    borrowing_limit INTEGER NOT NULL CHECK (borrowing_limit >= 0),
    daily_late_fee_rate NUMERIC(6,2) NOT NULL
        CHECK (daily_late_fee_rate >= 0 AND daily_late_fee_rate <> CAST('NaN' AS NUMERIC))
);

CREATE TABLE library.client (
    client_id INTEGER GENERATED BY DEFAULT AS IDENTITY CHECK (client_id > 0),
    first_name VARCHAR(100) NOT NULL CHECK (first_name ~ '[^[:space:]]'),
    last_name VARCHAR(100) NOT NULL CHECK (last_name ~ '[^[:space:]]'),
    phone_number VARCHAR(32) NOT NULL CHECK (phone_number ~ '[^[:space:]]'),
    membership_type_id INTEGER NOT NULL,
    account_status VARCHAR(10) NOT NULL DEFAULT 'active',
    PRIMARY KEY (client_id),
    FOREIGN KEY (membership_type_id) REFERENCES library.membership_type (membership_type_id)
        ON DELETE RESTRICT,
    CHECK (account_status IN ('active', 'inactive', 'restricted'))
);

CREATE TABLE library.library_item (
    item_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (item_id > 0),
    title VARCHAR(255) NOT NULL CHECK (title ~ '[^[:space:]]'),
    item_type VARCHAR(13) NOT NULL CHECK (item_type IN ('book', 'digital_media', 'magazine')),
    availability_status VARCHAR(12) NOT NULL DEFAULT 'available'
        CHECK (availability_status IN ('available', 'on_loan', 'reserved')),
    borrowing_restricted BOOLEAN NOT NULL DEFAULT FALSE,
    author_creator VARCHAR(255),
    isbn VARCHAR(13) CHECK (isbn ~ '^([0-9]{9}[0-9X]|[0-9]{13})$'),
    publication_year SMALLINT,
    genre VARCHAR(100),
    issue_number VARCHAR(50),
    publication_date DATE,
    CONSTRAINT applicable_item_fields CHECK (
        (item_type IN ('book', 'digital_media')
         AND author_creator IS NOT NULL AND author_creator ~ '[^[:space:]]'
         AND publication_year IS NOT NULL AND publication_year BETWEEN 1 AND 9999
         AND genre IS NOT NULL AND genre ~ '[^[:space:]]'
         AND issue_number IS NULL AND publication_date IS NULL)
        OR
        (item_type = 'magazine' AND author_creator IS NULL AND isbn IS NULL
         AND publication_year IS NULL AND genre IS NULL
         AND issue_number IS NOT NULL AND issue_number ~ '[^[:space:]]'
         AND publication_date IS NOT NULL)
    )
);

CREATE TABLE library.loan (
    loan_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (loan_id > 0),
    item_id INTEGER NOT NULL REFERENCES library.library_item ON DELETE RESTRICT,
    client_id INTEGER NOT NULL REFERENCES library.client ON DELETE RESTRICT,
    checkout_timestamp TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    due_date DATE NOT NULL,
    return_timestamp TIMESTAMPTZ,
    UNIQUE (loan_id, client_id),
    CONSTRAINT valid_due_date CHECK (
        due_date >= CAST(checkout_timestamp AT TIME ZONE 'America/Chicago' AS DATE)
    ),
    CONSTRAINT valid_return CHECK (return_timestamp >= checkout_timestamp)
);
-- Only open loans count.
CREATE UNIQUE INDEX one_active_loan_per_item ON library.loan (item_id)
    WHERE return_timestamp IS NULL;
CREATE INDEX loan_client_id_idx ON library.loan (client_id);
CREATE INDEX loan_active_due_date_idx ON library.loan (due_date) WHERE return_timestamp IS NULL;

CREATE TABLE library.late_fee (
    fee_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (fee_id > 0),
    loan_id INTEGER NOT NULL REFERENCES library.loan ON DELETE RESTRICT,
    amount_owed NUMERIC(10,2) NOT NULL,
    amount_paid NUMERIC(10,2) NOT NULL DEFAULT 0,
    UNIQUE (loan_id),
    CONSTRAINT valid_fee_amounts CHECK (
        amount_owed <> CAST('NaN' AS NUMERIC)
        AND amount_paid BETWEEN 0 AND amount_owed
    )
);

CREATE TABLE library.reservation (
    reservation_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (reservation_id > 0),
    client_id INTEGER NOT NULL REFERENCES library.client ON DELETE RESTRICT,
    item_id INTEGER NOT NULL REFERENCES library.library_item ON DELETE RESTRICT,
    reservation_date DATE NOT NULL DEFAULT CAST(CURRENT_TIMESTAMP AT TIME ZONE 'America/Chicago' AS DATE),
    reservation_status VARCHAR(10) NOT NULL DEFAULT 'pending',
    UNIQUE (reservation_id, client_id)
);
ALTER TABLE library.reservation ADD CONSTRAINT valid_reservation_status
    CHECK (reservation_status IN ('pending', 'available', 'fulfilled', 'cancelled'));
CREATE UNIQUE INDEX one_open_reservation_per_client_item ON library.reservation (client_id, item_id)
    WHERE reservation_status IN ('pending', 'available');
CREATE UNIQUE INDEX one_available_reservation_per_item ON library.reservation (item_id)
    WHERE reservation_status = 'available';
CREATE INDEX reservation_queue_idx ON library.reservation (item_id, reservation_date, reservation_id)
    WHERE reservation_status IN ('pending', 'available');
CREATE INDEX reservation_client_id_idx ON library.reservation (client_id);

CREATE TABLE library.notification (
    notification_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (notification_id > 0),
    client_id INTEGER NOT NULL REFERENCES library.client ON DELETE RESTRICT,
    loan_id INTEGER,
    reservation_id INTEGER,
    notification_type VARCHAR(21) NOT NULL,
    message TEXT NOT NULL CHECK (message ~ '[^[:space:]]'),
    creation_timestamp TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (loan_id, client_id) REFERENCES library.loan (loan_id, client_id) ON DELETE RESTRICT,
    FOREIGN KEY (reservation_id, client_id)
        REFERENCES library.reservation (reservation_id, client_id) ON DELETE RESTRICT,
    CONSTRAINT one_notice_source CHECK (
        (notification_type IN ('upcoming_due', 'overdue') AND loan_id IS NOT NULL AND reservation_id IS NULL)
        OR (notification_type = 'reservation_available' AND reservation_id IS NOT NULL AND loan_id IS NULL)
    )
);
CREATE INDEX notification_client_id_idx ON library.notification (client_id);
CREATE UNIQUE INDEX one_loan_notice_per_type_day ON library.notification
    (loan_id, notification_type, CAST(creation_timestamp AT TIME ZONE 'America/Chicago' AS DATE))
    WHERE loan_id IS NOT NULL;
CREATE INDEX notification_reservation_id_idx ON library.notification (reservation_id)
    WHERE reservation_id IS NOT NULL;
CREATE INDEX client_membership_type_id_idx ON library.client (membership_type_id);

-- keep library tables private
ALTER TABLE library.membership_type ENABLE ROW LEVEL SECURITY;
ALTER TABLE library.client ENABLE ROW LEVEL SECURITY;
ALTER TABLE library.library_item ENABLE ROW LEVEL SECURITY;
ALTER TABLE library.loan ENABLE ROW LEVEL SECURITY;
ALTER TABLE library.late_fee ENABLE ROW LEVEL SECURITY;
ALTER TABLE library.reservation ENABLE ROW LEVEL SECURITY;
ALTER TABLE library.notification ENABLE ROW LEVEL SECURITY;
COMMIT;
